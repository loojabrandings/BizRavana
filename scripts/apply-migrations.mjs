/**
 * Apply pending SQL migrations from supabase/migrations/ to Supabase.
 *
 * Reads DATABASE_URL from .env.local (falling back to process.env) and
 * connects directly to PostgreSQL — no Supabase CLI or access token needed.
 *
 * Every applied migration is recorded in supabase_migrations.schema_migrations
 * so the Supabase dashboard stops reporting "No migrations" and future runs
 * only apply what is actually missing.
 *
 * Usage:
 *   node scripts/apply-migrations.mjs                       # apply pending migrations (uses .env.local)
 *   node scripts/apply-migrations.mjs --dry-run             # report state only, no changes
 *   node scripts/apply-migrations.mjs --baseline            # record existing files as applied (prod already migrated via SQL editor)
 *   node scripts/apply-migrations.mjs --apply-all           # allow running from 001 on a genuinely fresh database
 *   node scripts/apply-migrations.mjs --no-backup           # skip the pre-migration logical backup
 *   node scripts/apply-migrations.mjs --env .env.staging.local  # use a specific env file (e.g. staging)
 */

import { createHash } from "node:crypto";
import { readFileSync, existsSync, mkdirSync, writeFileSync, readdirSync } from "node:fs";
import { resolve, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = resolve(__dirname, "..", "supabase", "migrations");
const BACKUPS_DIR = resolve(__dirname, "..", "backups");

const argList = process.argv.slice(2);
const args = new Set(argList);
const DRY_RUN = args.has("--dry-run");
const BASELINE = args.has("--baseline");
const APPLY_ALL = args.has("--apply-all");
const NO_BACKUP = args.has("--no-backup");
const envFlagIndex = argList.indexOf("--env");
const ENV_FILE = envFlagIndex !== -1 && argList[envFlagIndex + 1] ? argList[envFlagIndex + 1] : ".env.local";

if (args.has("--help") || args.has("-h")) {
  console.log(`Usage: node scripts/apply-migrations.mjs [--dry-run] [--baseline] [--apply-all] [--no-backup] [--env FILE]`);
  process.exit(0);
}

/** Parse a .env file into an object (last occurrence wins). */
function loadEnvFile(filePath) {
  if (!existsSync(filePath)) return {};
  const env = {};
  for (const line of readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

function checksum(sql) {
  return createHash("sha256").update(sql).digest("hex");
}

function maskUrl(url) {
  return String(url).replace(/(postgres(ql)?:\/\/[^:]+:)[^@]+(@)/, "$1***$3");
}

/** Quote one SQL literal for a generated INSERT statement. */
function sqlLiteral(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (Buffer.isBuffer(value)) return `'\\x${value.toString("hex")}'::bytea`;
  if (value instanceof Date) return `'${value.toISOString()}'::timestamptz`;
  let text;
  if (typeof value === "object") {
    text = JSON.stringify(value);
  } else {
    text = String(value);
  }
  return `'${text.replace(/'/g, "''")}'`;
}

/**
 * Logical backup of every public-schema table as INSERT statements.
 * Restore with:  psql "$DATABASE_URL" -f <file>
 */
async function backupDatabase(client, reason) {
  mkdirSync(BACKUPS_DIR, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const file = resolve(BACKUPS_DIR, `bizravana-${reason}-${stamp}.sql`);
  const { rows: tables } = await client.query(
    `SELECT table_name FROM information_schema.tables
      WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
      ORDER BY table_name`,
  );
  const lines = [
    `-- BizRavana logical backup (generated by scripts/apply-migrations.mjs)`,
    `-- Created: ${new Date().toISOString()} (${tables.length} tables)`,
    `-- Restore: psql "$DATABASE_URL" -f ${basename(file)}`,
    "BEGIN;",
  ];
  for (const { table_name: table } of tables) {
    const { rows, fields } = await client.query(`SELECT * FROM "public"."${table}"`);
    for (const row of rows) {
      const values = fields.map((f) => sqlLiteral(row[f.name])).join(", ");
      lines.push(`INSERT INTO "public"."${table}" VALUES (${values});`);
    }
    lines.push(`-- ${table}: ${rows.length} rows`);
  }
  lines.push("COMMIT;");
  writeFileSync(file, lines.join("\n") + "\n");
  return { file, tableCount: tables.length };
}

async function main() {
  const env = { ...loadEnvFile(resolve(__dirname, "..", ENV_FILE)), ...process.env };
  const connectionString = env.DATABASE_URL;
  if (!connectionString) {
    console.error("❌ DATABASE_URL is required. Add it to .env.local");
    console.error("   Get it from: Supabase Dashboard → Project Settings → Database → Connection string");
    process.exit(1);
  }

  const { default: pg } = await import("pg");
  const client = new pg.Client({ connectionString });
  await client.connect();
  console.log(`✅ Connected to Supabase PostgreSQL (${maskUrl(connectionString)})`);

  const files = readdirSync(MIGRATIONS_DIR)
    .filter((name) => /^\d{3}_[a-z0-9_]+\.sql$/.test(name))
    .sort();

  const existsRes = await client.query(
    `SELECT to_regclass('supabase_migrations.schema_migrations') AS t`,
  );
  const historyExists = existsRes.rows[0].t !== null;

  if (!historyExists) {
    if (DRY_RUN) {
      console.log(`ℹ️  Migration history table is missing. All ${files.length} files are unrecorded.`);
      console.log(`   • Production already migrated via SQL editor  → run with --baseline`);
      console.log(`   • Fresh database with no migrations applied  → run with --apply-all`);
      await client.end();
      return;
    }
    await client.query(`CREATE SCHEMA IF NOT EXISTS supabase_migrations`);
    await client.query(`
      CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations (
        version    TEXT PRIMARY KEY,
        name       TEXT NOT NULL,
        checksum   TEXT NOT NULL,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )`);
    console.log("✅ Created supabase_migrations.schema_migrations (migration history)");
  }

  const recordedRes = await client.query(
    `SELECT version, checksum FROM supabase_migrations.schema_migrations`,
  );
  const recorded = new Map(recordedRes.rows.map((r) => [r.version, r.checksum]));

  const pending = files.filter((name) => !recorded.has(name.slice(0, 3)));

  if (DRY_RUN) {
    console.log(`📁 ${files.length} migration files, ${recorded.size} recorded, ${pending.length} pending`);
    if (pending.length === 0) {
      console.log("✅ Database is up to date — nothing to apply.");
    } else {
      for (const name of pending) console.log(`   pending: ${name}`);
    }
    await client.end();
    return;
  }

  if (BASELINE) {
    let added = 0;
    for (const name of files) {
      const version = name.slice(0, 3);
      if (recorded.has(version)) continue;
      const sql = readFileSync(resolve(MIGRATIONS_DIR, name), "utf8");
      await client.query(
        `INSERT INTO supabase_migrations.schema_migrations (version, name, checksum)
         VALUES ($1, $2, $3)`,
        [version, name, checksum(sql)],
      );
      added++;
    }
    console.log(`✅ Baseline recorded: ${added} migration(s) marked as applied (nothing was executed).`);
    await client.end();
    return;
  }

  if (recorded.size === 0 && !APPLY_ALL) {
    console.error("⚠️  Migration history is empty but the database may already be migrated (SQL editor deployments are not recorded).");
    console.error("   • Production: run `node scripts/apply-migrations.mjs --baseline` to record existing state, then re-run.");
    console.error("   • Fresh DB:   run `node scripts/apply-migrations.mjs --apply-all` to apply everything from 001.");
    await client.end();
    process.exit(1);
  }

  if (pending.length === 0) {
    console.log(`✅ Database is up to date (${recorded.size} migrations recorded, none pending).`);
    await client.end();
    return;
  }

  console.log(`\n⏳ ${pending.length} pending migration(s):`);
  for (const name of pending) console.log(`   - ${name}`);

  if (!NO_BACKUP) {
    const backup = await backupDatabase(client, "pre-migration");
    console.log(`💾 Pre-migration backup written: ${backup.file} (${backup.tableCount} tables)`);
  }

  let applied = 0;
  for (const name of pending) {
    const version = name.slice(0, 3);
    const sql = readFileSync(resolve(MIGRATIONS_DIR, name), "utf8");
    try {
      await client.query("BEGIN");
      await client.query(sql);
      await client.query(
        `INSERT INTO supabase_migrations.schema_migrations (version, name, checksum)
         VALUES ($1, $2, $3)`,
        [version, name, checksum(sql)],
      );
      await client.query("COMMIT");
      console.log(`   ✅ ${name}`);
      applied++;
    } catch (err) {
      await client.query("ROLLBACK");
      console.error(`   ❌ ${name} FAILED — rolled back.`);
      console.error(`      ${err.message}`);
      console.error(`   ℹ️  No further migrations were applied. The backup above can restore the previous state.`);
      await client.end();
      process.exit(1);
    }
  }

  console.log(`\n✅ Migration run complete: ${applied} applied, database now at version ${pending.at(-1).slice(0, 3)}.`);
  await client.end();
}

main().catch((err) => {
  console.error("❌ Unexpected error:", err.message);
  process.exit(1);
});
